#!/usr/bin/env python3
"""
FlashOcc official occupancy visualizer, simplified for qualitative comparison.

Based on tools/analysis_tools/vis_occ.py:
- keeps the official voxel conversion and front-overlook Open3D viewpoint;
- uses the requested semantic color palette;
- saves Prediction and Ground Truth separately;
- saves the six original camera images separately;
- does not generate a collage or video;
- associates predictions with samples through scene_name/sample_token/pred.npz.
"""

